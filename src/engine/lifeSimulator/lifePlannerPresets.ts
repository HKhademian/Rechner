export function buildLifePlannerPreset(id: LifePlannerPresetId): LifePlanInput {
  const found = LIFE_PLANNER_PRESETS.find((preset) => preset.id === id);
  if (!found) {
    throw new TypeError(`Unknown LifePlannerPresetId: ${id}`);
  }
  return found.buildPlan();
}
